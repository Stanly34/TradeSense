async function main() {
  let created = 0
  let updated = 0
  for (const firm of FIRMS) {
    const { slug, ...data } = firm
    const exists = await prisma.propFirm.findUnique({ where: { slug } })
    if (exists) {
      await prisma.propFirm.update({
        where: { slug },
        data: { ...data, codeStatus: 'OK', lastCodeCheckAt: null, rulesStatus: 'OK', lastRulesCheckAt: null },
      })
      updated++
    } else {
      await prisma.propFirm.create({
        data: { slug, ...data, codeStatus: 'OK', lastCodeCheckAt: null, rulesStatus: 'OK', lastRulesCheckAt: null },
      })
      created++
    }
  }
  console.log(`Prop firms seeded: ${created} created, ${updated} updated`)
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (invokedDirectly) {
  main()
    .catch((e) => {
      console.error(e)
      process.exit(1)
    })
    .finally(() => prisma.$disconnect())
}
