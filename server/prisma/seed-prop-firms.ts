import { PrismaClient } from '@prisma/client'

const prisma = new PrismaClient()

interface Rule {
  label: string
  value: string
}

interface SeedSize {
  size: string
  price: number
  discounted: number
  evalRules: Rule[]
  fundedRules: Rule[]
}

interface SeedPlan {
  plan: string
  planDesc: string
  sizes: SeedSize[]
  fundedRules?: Rule[]
}

interface SeedFirm {
  name: string
  slug: string
  websiteUrl: string
  description: string
  rating: number
  country: string
  instruments: string
  profitSplit: number
  payoutSpeed: string
  logoColor: string
  accountPrices: SeedPlan[]
  discountPercent: number
  promoCode: string | null
  promoSourceUrl: string | null
  rulesSourceUrl: string | null
  dailyPayouts: boolean
  noActivationFee: boolean
  oneTimeFee: boolean
  instantFunding: boolean
  isFeatured: boolean
  dealEndsAt: string | null
}

function pct(price: number, discountPercent: number): number {
  return Math.round(price * (1 - discountPercent / 100))
}

const r = (label: string, value: string): Rule => ({ label, value })

const f = (...rows: [string, string][]): Rule[] => rows.map(([label, value]) => ({ label, value }))

function size(
  sizeName: string,
  price: number,
  evalRules: Rule[],
  fundedRules?: Rule[],
): SeedSize {
  return { size: sizeName, price, discounted: price, evalRules, fundedRules: fundedRules ?? [] }
}

function plan(name: string, planDesc: string, sizes: SeedSize[], fundedRules?: Rule[]): SeedPlan {
  return { plan: name, planDesc, sizes, fundedRules }
}

function applyDiscount(firms: SeedFirm[]) {
  for (const firm of firms) {
    for (const p of firm.accountPrices) {
      for (const s of p.sizes) {
        s.discounted = pct(s.price, firm.discountPercent)
        if (!s.fundedRules?.length && p.fundedRules?.length) s.fundedRules = p.fundedRules
      }
    }
  }
}

